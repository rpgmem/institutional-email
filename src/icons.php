declare(strict_types=1);

namespace InstitutionalEmail;

/**
 * Line icons drawn in the text colour, so they follow the palette, light or
 * dark. The drawings are Free Form Certificate's (its `Core\Icons`), copied
 * rather than shared because this plugin works without that one: 24×24, a
 * stroke in `currentColor`, and only geometry, never a colour, a style or a
 * script of their own.
 *
 * Two ways in, one drawing. `svg()` prints an icon inline for markup the
 * plugin writes itself (the settings screen's tabs and headings). The
 * `.ie-icon-<name>` classes draw the icons in MASKED as a CSS mask on
 * `::before`, from `assets/css/icons.css`, which `stylesheet()` writes: that
 * is how a button carries its icon, and why a script that rewrites the
 * button's label keeps it.
 */
final class Icons {

