	/**
	 * The icons markup reaches through a `.ie-icon-<name>` class: the
	 * buttons' and the screenshot viewer's. Only these are in the
	 * stylesheet, so the form's page carries no drawing it never shows.
	 */
	public const MASKED = array( 'check', 'chevron-left', 'chevron-right', 'copy', 'external', 'minus', 'plus', 'save', 'x' );

	/**
	 * The first line of `assets/css/icons.css`.
	 */
	public const CSS_HEADER = '/* Generated by InstitutionalEmail\Icons::stylesheet(); do not edit by hand. Regenerate with IE_UPDATE_ICON_CSS=1 vendor/bin/phpunit --filter ButtonStylesTest. */';

	/**
	 * Whether an icon exists.
	 *
	 * @param string $name Icon name.
	 */
	public static function has( string $name ): bool {
		return isset( self::PATHS[ $name ] );
	}

	/**
	 * Whether an icon can be reached through a `.ie-icon-<name>` class.
	 *
	 * @param string $name Icon name.
	 */
	public static function masked( string $name ): bool {
		return in_array( $name, self::MASKED, true ) && self::has( $name );
	}

	/**
	 * Every icon name.
	 *
	 * @return list<string>
	 */
	public static function names(): array {
		return array_keys( self::PATHS );
	}

	/**
	 * The icon as inline SVG, hidden from assistive technology because the
	 * text beside it says the same; '' for an unknown name.
	 *
	 * @param string $name Icon name.
	 * @param int    $size Width and height in pixels.
	 */
	public static function svg( string $name, int $size = 20 ): string {
		if ( ! self::has( $name ) ) {
			return '';
		}
		return sprintf(
			'<svg class="ie-icon" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="%1$d" height="%1$d" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">%2$s</svg>',
			max( 1, $size ),
			self::PATHS[ $name ]
		);
	}

	/**
	 * The whole of `assets/css/icons.css`.
	 *
	 * Each icon is a mask over the text colour, in `::before` with no
	 * content, which keeps it out of the accessibility tree. Sizes are in
	 * `em`, so the icon scales with the text beside it. Under forced colours
	 * the system replaces every background, which would erase the mask, so
	 * the pseudo-element opts out and paints in the system text colour.
	 */
	public static function stylesheet(): string {
		$selectors = array();
		$rules     = array();
		foreach ( self::MASKED as $name ) {
			$selector    = '.ie-icon-' . $name . '::before';
			$selectors[] = $selector;
			$url         = 'url("data:image/svg+xml,' . self::dataUriBody( $name ) . '")';
			$rules[]     = $selector . " {\n\t-webkit-mask-image: " . $url . ";\n\tmask-image: " . $url . ";\n}";
		}

		$base = implode( ",\n", $selectors ) . " {\n"
			. "\tcontent: \"\";\n"
			. "\tdisplay: inline-block;\n"
			. "\tflex-shrink: 0;\n"
			. "\twidth: 1.15em;\n"
			. "\theight: 1.15em;\n"
			. "\tmargin-right: 0.4em;\n"
			. "\tvertical-align: -0.2em;\n"
			. "\tbackground-color: currentColor;\n"
			. "\t-webkit-mask-repeat: no-repeat;\n"
			. "\tmask-repeat: no-repeat;\n"
			. "\t-webkit-mask-position: center;\n"
			. "\tmask-position: center;\n"
			. "\t-webkit-mask-size: contain;\n"
			. "\tmask-size: contain;\n"
			. '}';

		$forced = "@media (forced-colors: active) {\n"
			. "\t" . implode( ",\n\t", $selectors ) . " {\n"
			. "\t\tforced-color-adjust: none;\n"
			. "\t\tbackground-color: CanvasText;\n"
			. "\t}\n"
			. '}';

		return self::CSS_HEADER . "\n\n" . $base . "\n\n" . implode( "\n\n", $rules ) . "\n\n" . $forced . "\n";
	}

	/**
	 * A standalone SVG for a data URI, percent-encoded where CSS needs it.
	 * `currentColor` in a standalone image resolves to black, which is all a
	 * mask needs: only the alpha channel is read.
	 *
	 * @param string $name Icon name.
	 */
	private static function dataUriBody( string $name ): string {
		$svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">'
			. self::PATHS[ $name ]
			. '</svg>';
		return strtr(
			str_replace( '"', "'", $svg ),
			array(
				'<' => '%3C',
				'>' => '%3E',
				'#' => '%23',
			)
		);
	}
}
